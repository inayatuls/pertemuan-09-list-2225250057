
nilai = [75, 80, 65, 90, 88]

# Mengakses elemen menggunakan indeks
print("Data pertama:", nilai[0])
print("Data kedua:", nilai[1])
print("Data terakhir:", nilai[-1])

# Mengakses beberapa elemen menggunakan slicing
print("Data indeks 1 sampai 3:", nilai[1:4])
print("Tiga data pertama:", nilai[:3])
print("Dua data terakhir:", nilai[-2:])